import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile, mkdir} from 'node:fs/promises';
import {testOrigin, assertLocalTestLink} from './target.mjs';
const origin=testOrigin();
await mkdir('qa',{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream','--auto-select-desktop-capture-source=Entire screen']});
const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['camera','microphone','clipboard-read','clipboard-write']});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(origin+'/',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:/Video calls that bring/}).waitFor();
 await page.screenshot({path:'qa/home-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'New meeting',exact:true}).click();
 await page.getByRole('menuitem',{name:'Create a meeting for later'}).click();
 await page.getByRole('heading',{name:'Your meeting is ready'}).waitFor();
 const link=await page.getByRole('textbox',{name:'Meeting link',exact:true}).inputValue();
 assertLocalTestLink(link,origin);
 await writeFile('qa/meeting-test.json',JSON.stringify({link}));
 await page.getByRole('button',{name:'Copy meeting link',exact:true}).click();
 assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),link);
 await page.getByRole('button',{name:'Done',exact:true}).click();
 await page.getByRole('textbox',{name:'Enter a code or link'}).fill(link);
 await page.getByRole('button',{name:'Join',exact:true}).first().click();
 await page.getByRole('heading',{name:'Ready to join?'}).waitFor();
 await page.screenshot({path:'qa/prejoin.png',fullPage:true});
 console.log('Prejoin inputs:',await page.locator('input').evaluateAll(nodes=>nodes.map(n=>({name:n.name,placeholder:n.placeholder,type:n.type,id:n.id}))));
 console.log('Prejoin buttons:',await page.getByRole('button').allTextContents());
 await page.locator('input[name="username"]').fill('Alex Test');
 await page.getByRole('button',{name:'Join now',exact:true}).click();
 await page.locator('.call-header').waitFor({timeout:30000});
 await page.screenshot({path:'qa/call-first.png',fullPage:true});
 console.log('Call controls:',await page.getByRole('button').allTextContents());
 console.log('PASS: home, create link, copy link, join via link, prejoin and live call UI.');
 assert.deepEqual(errors,[]);
 await page.getByRole('button',{name:/Leave/i}).click();
 await page.getByRole('heading',{name:'You’ve left the meeting.'}).waitFor();
 await page.getByRole('button',{name:'Return to home'}).click();
 await page.getByRole('button',{name:'Schedule a meeting',exact:true}).click();
 await page.getByRole('textbox',{name:'Meeting title'}).fill('Browser QA scheduled catch-up');
 const create=page.waitForResponse(r=>r.url().endsWith('/api/meetings')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Schedule meeting',exact:true}).click();
 assert.equal((await create).status(),201);
 await page.getByRole('heading',{name:'Your meeting is scheduled'}).waitFor();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download calendar invite'}).click();
 const download=await downloadPromise;await download.saveAs('qa/scheduled-invite.ics');
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.reload({waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Browser QA scheduled catch-up'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'qa/home-mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 console.log('PASS: leave meeting, schedule, calendar download, reload persistence and mobile layout.');
 assert.deepEqual(errors,[]);
}finally{await browser.close();}
